"""Report orchestration: compress -> Hermes (or offline fallback) -> spoiler guard -> pretty output."""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any, Optional

from .adapters import HermesClient, HermesError, LocalReportGenerator
from .compressor import CompressedTrajectory, CompressorConfig, compress

MODES = ("student", "instructor")
_CODE_BLOCK = re.compile(r"```[^\n]*\n(.*?)```", re.S)


def spoiler_guard(markdown: str, max_lines: int = 2, lang: str = "en") -> str:
    """Remove multi-line code blocks from student-facing text (LLMs love to 'just show the fix')."""
    note = "_(код скрыт — попробуй сначала сам)_" if lang == "ru" else "_(code hidden — try it yourself first)_"

    def repl(m: "re.Match[str]") -> str:
        body = m.group(1).strip("\n")
        return m.group(0) if body.count("\n") + 1 <= max_lines else note
    return _CODE_BLOCK.sub(repl, markdown)


@dataclass
class Report:
    mode: str
    markdown: str
    source: str                         # "hermes" | "offline"
    context: CompressedTrajectory
    warning: Optional[str] = None

    def _footer(self) -> str:
        src = "Hermes LLM" if self.source == "hermes" else "offline engine"
        st = self.context.stats
        f = (f"\n\n---\n<sub>stucktrace · {self.mode} report · generated by {src} · "
             f"{st.get('raw_events')} raw events → {st.get('compressed_bytes')} B context "
             f"({st.get('ratio')}× smaller)</sub>")
        if self.warning:
            f += f"\n<sub>⚠ {self.warning}</sub>"
        return f

    def _repr_markdown_(self) -> str:   # auto-rendered in Jupyter
        return self.markdown + self._footer()

    def __str__(self) -> str:
        return self.markdown

    def save(self, path: str) -> str:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(self.markdown + self._footer() + "\n")
        return path

    def display(self) -> None:
        try:
            from IPython.display import Markdown, display  # type: ignore
            display(Markdown(self._repr_markdown_()))
        except Exception:
            print(self._repr_markdown_())


def generate_report(
    mode: str = "student",
    session: Any = None,
    backend: str = "auto",
    lang: str = "en",
    hermes: Optional[HermesClient] = None,
    config: Optional[CompressorConfig] = None,
    display: bool = False,
) -> Report:
    """Generate a Student Self-Reflection or Instructor Diagnostic report.

    backend: ``"auto"`` (Hermes if configured, else offline), ``"hermes"``
    (try Hermes, fall back with a warning) or ``"offline"``.
    The function never raises because of the network.
    """
    from .tracker import get_session

    if mode not in MODES:
        raise ValueError(f"mode must be one of {MODES}, got {mode!r}")
    if isinstance(session, CompressedTrajectory):
        ctx = session
    else:
        ctx = compress(session if session is not None else get_session(), config)

    client = hermes or HermesClient()
    text, source, warning = None, "offline", None
    if backend in ("auto", "hermes") and (client.available or backend == "hermes"):
        try:
            text = client.report(ctx, mode=mode, lang=lang)
            source = "hermes"
        except HermesError as exc:
            warning = f"Hermes unavailable, used offline report ({exc})"
        except Exception as exc:  # pragma: no cover - never let reporting crash a notebook
            warning = f"Hermes error, used offline report ({exc!r})"
    if text is None:
        text = LocalReportGenerator().generate(ctx, mode=mode, lang=lang)
    if mode == "student":
        text = spoiler_guard(text, lang=lang)

    rep = Report(mode=mode, markdown=text, source=source, context=ctx, warning=warning)
    if display:
        rep.display()
    return rep
